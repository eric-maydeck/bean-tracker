// One-off: Natural Earth 110m admin-0 countries (public domain) → src/lib/worldMap.ts, one SVG
// path per country in the Equal Earth projection, Antarctica dropped. Re-run only to change the
// source or projection: node scripts/build-world-map.ts [local-geojson-path]
import { readFileSync, writeFileSync } from 'node:fs';

const SRC =
  'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_admin_0_countries.geojson';
const SCALE = 180; // px per projected unit (Equal Earth spans about ±2.71 × ±1.32)

// Equal Earth (Šavrič, Patterson, Jenny 2018).
const [A1, A2, A3, A4] = [1.340264, -0.081106, 0.000893, 0.003796];
const M = Math.sqrt(3) / 2;
function project([lon, lat]: number[]): [number, number] {
  const l = (lon * Math.PI) / 180;
  const t = Math.asin(M * Math.sin((lat * Math.PI) / 180));
  const t2 = t * t;
  const t6 = t2 * t2 * t2;
  const x = (2 * Math.sqrt(3) * l * Math.cos(t)) / (3 * (A1 + 3 * A2 * t2 + t6 * (7 * A3 + 9 * A4 * t2)));
  return [x, t * (A1 + A2 * t2 + t6 * (A3 + A4 * t2))];
}

type Feature = { properties: { NAME: string; ISO_A2_EH: string }; geometry: { type: string; coordinates: unknown } };
const local = process.argv[2];
const geo = (local ? JSON.parse(readFileSync(local, 'utf8')) : await (await fetch(SRC)).json()) as {
  features: Feature[];
};
const countries = geo.features
  .filter((f) => f.properties.ISO_A2_EH !== 'AQ')
  .map((f) => {
    const polys = (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates) as number[][][][];
    return {
      iso: f.properties.ISO_A2_EH === '-99' ? '' : f.properties.ISO_A2_EH,
      name: f.properties.NAME,
      rings: polys.flat().map((ring) => ring.map(project))
    };
  });
const pts = countries.flatMap((c) => c.rings.flat());
const minX = Math.min(...pts.map((p) => p[0]));
const maxX = Math.max(...pts.map((p) => p[0]));
const minY = Math.min(...pts.map((p) => p[1]));
const maxY = Math.max(...pts.map((p) => p[1]));
const r1 = (n: number) => Math.round(n * 10) / 10;
const d = (rings: [number, number][][]) =>
  rings.map((ring) => 'M' + ring.map(([x, y]) => `${r1((x - minX) * SCALE)},${r1((maxY - y) * SCALE)}`).join('L') + 'Z').join('');

const rows = countries.map((c) => JSON.stringify({ iso: c.iso, name: c.name, d: d(c.rings) }));
writeFileSync(
  'src/lib/worldMap.ts',
  `// Generated by scripts/build-world-map.ts from Natural Earth 110m admin-0 countries (public domain):
// ${SRC}
// Equal Earth projection, Antarctica dropped. Don't edit by hand.
export const WORLD_VIEWBOX = '0 0 ${Math.ceil((maxX - minX) * SCALE)} ${Math.ceil((maxY - minY) * SCALE)}';
export const WORLD: { iso: string; name: string; d: string }[] = [
${rows.join(',\n')}
];
`
);
console.log(`worldMap.ts: ${countries.length} countries`);
