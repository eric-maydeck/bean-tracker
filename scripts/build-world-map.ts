// One-off: Natural Earth admin-0 countries (public domain) → src/lib/worldMap.ts (110m) or
// src/lib/worldMap50.ts (50m), one SVG path per country in the Equal Earth projection, Antarctica
// dropped. Both resolutions share the offsets below (measured on 110m) so coordinates line up.
// Re-run only to change the source or projection:
//   node scripts/build-world-map.ts [110m|50m] [local-geojson-path]
import { readFileSync, writeFileSync } from 'node:fs';

const RES = process.argv[2] ?? '110m';
if (RES !== '110m' && RES !== '50m') throw new Error('resolution must be 110m or 50m');
const SRC = `https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_${RES}_admin_0_countries.geojson`;
const OUT = RES === '110m' ? 'src/lib/worldMap.ts' : 'src/lib/worldMap50.ts';
const SCALE = 180; // px per projected unit (Equal Earth spans about ±2.71 × ±1.32)
// Fixed from the 110m extent (min projected x, max projected y) so 50m is not re-fitted.
const MIN_X = -2.6559786979099256;
const MAX_Y = 1.3054284640211966;
const VIEWBOX = '0 0 957 420';

// Equal Earth (Šavrič, Patterson, Jenny 2018).
const [A1, A2, A3, A4] = [1.340264, -0.081106, 0.000893, 0.003796];
const M = Math.sqrt(3) / 2;
function project([lon, lat]: number[]): [number, number] {
  const l = (lon * Math.PI) / 180;
  const t = Math.asin(M * Math.sin((lat * Math.PI) / 180));
  const t2 = t * t;
  const t6 = t2 * t2 * t2;
  const x = (2 * Math.sqrt(3) * l * Math.cos(t)) / (3 * (A1 + 3 * A2 * t2 + t6 * (7 * A3 + 9 * A4 * t2)));
  return [x, t * (A1 + A2 * t2 + t6 * (A3 + A4 * t2))];
}

type Feature = { properties: { NAME: string; ISO_A2_EH: string }; geometry: { type: string; coordinates: unknown } };
const local = process.argv[3];
const geo = (local ? JSON.parse(readFileSync(local, 'utf8')) : await (await fetch(SRC)).json()) as {
  features: Feature[];
};
const countries = geo.features
  .filter((f) => f.properties.ISO_A2_EH !== 'AQ')
  .map((f) => {
    const polys = (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates) as number[][][][];
    return {
      iso: f.properties.ISO_A2_EH === '-99' ? '' : f.properties.ISO_A2_EH,
      name: f.properties.NAME,
      rings: polys.flat().map((ring) => ring.map(project))
    };
  });
const r1 = (n: number) => Math.round(n * 10) / 10;
const d = (rings: [number, number][][]) =>
  rings
    .map((ring) => {
      const pts = ring.map(([x, y]) => `${r1((x - MIN_X) * SCALE)},${r1((MAX_Y - y) * SCALE)}`);
      return 'M' + pts.filter((p, i) => p !== pts[i - 1]).join('L') + 'Z';
    })
    .join('');

// Merge features sharing a key (iso || name) so keys are unique per file.
const merged = new Map<string, { iso: string; name: string; rings: [number, number][][] }>();
for (const c of countries) {
  const k = c.iso || c.name;
  const m = merged.get(k);
  if (m) m.rings.push(...c.rings);
  else merged.set(k, { ...c, rings: [...c.rings] });
}
const rows = [...merged.values()].map((c) => JSON.stringify({ iso: c.iso, name: c.name, d: d(c.rings) }));
writeFileSync(
  OUT,
  `// Generated by scripts/build-world-map.ts from Natural Earth ${RES} admin-0 countries (public domain):
// ${SRC}
// Equal Earth projection, Antarctica dropped. Don't edit by hand.
export const WORLD_VIEWBOX = '${VIEWBOX}';
export const WORLD: { iso: string; name: string; d: string }[] = [
${rows.join(',\n')}
];
`
);
console.log(`${OUT}: ${rows.length} countries`);
