// Regenerates src/lib/server/recaps/flags.ts: the circle-flags SVGs (HatScripts, MIT) for the ISO codes countryFlags.ts knows,
// packed into one module for the link-preview cards (satori graphemeImages). Fetches the npm tarball here only, never at render time.
//   node scripts/gen-flags.ts
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { COUNTRY_NAMES, isoCode } from '../src/lib/countryFlags.ts';

const VERSION = '2.8.3';
const dir = mkdtempSync(join(tmpdir(), 'circle-flags-'));
const tgz = execFileSync('npm', ['pack', `circle-flags@${VERSION}`, '--pack-destination', dir], { cwd: dir, encoding: 'utf8' }).trim().split('\n').pop()!;
execFileSync('tar', ['xzf', tgz], { cwd: dir });
const licence = readFileSync(join(dir, 'package', 'LICENSE.md'), 'utf8').trim();

const flags: Record<string, string> = {};
const missing: string[] = [];
for (const code of new Set(COUNTRY_NAMES.map((n) => isoCode(n)!.toLowerCase()))) {
  try {
    flags[code] = readFileSync(join(dir, 'package', 'flags', `${code}.svg`), 'utf8').trim().replace(/>\s+</g, '><');
  } catch { missing.push(code); }
}

const header = `// GENERATED by scripts/gen-flags.ts: do not edit. Flag SVGs from circle-flags ${VERSION}
// https://github.com/HatScripts/circle-flags (npm: circle-flags), MIT licence:
//
${licence.split('\n').map((l) => `// ${l}`.trimEnd()).join('\n')}
`;
const body = `\n// ISO 3166-1 alpha-2 (lower case) -> SVG source.\nexport const FLAG_SVG: Record<string, string> = ${JSON.stringify(flags)};\n`;
writeFileSync(new URL('../src/lib/server/recaps/flags.ts', import.meta.url), header + body);
console.log(`${Object.keys(flags).length} flags, ${((header + body).length / 1024).toFixed(0)} KB${missing.length ? `; no flag for: ${missing.join(', ')}` : ''}`);
